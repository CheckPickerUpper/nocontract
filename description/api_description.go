func (Patch) Name() string { return http.MethodPatch }

// Name is DELETE.
func (Delete) Name() string { return http.MethodDelete }

// Body is absent: a GET request carries no body.
func (Get) Body() MethodBody { return BodyAbsent{} }

// Body is carried.
