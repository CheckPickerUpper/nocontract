// Package writing writes the Go file of one package: a Serving struct naming every receiver and
// guard its routes need, a Routes function that cannot be called without them, one function per
// route that reads its input and runs its handler, one exhaustive switch per outcome that writes
// each member with its tag, status and code, and the exported function each guard's refusal is
// answered through.
package writing

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"maps"
	"slices"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/samber/mo"

	"github.com/CheckPickerUpper/nocontract/description"
	"github.com/CheckPickerUpper/nocontract/go/serverplan"
)

// Header opens every file NoContract writes.
const Header = "// Code generated by nocontract. DO NOT EDIT.\n"

// StubOf is an existing generated file as it is read while the routes are read again: its imports,
// types and exported functions, each function's body only a panic. Code calling what the file
// declares still type-checks, and the file's own code, which may no longer compile, is not read.
func StubOf(existing []byte) mo.Result[[]byte] {
	files := token.NewFileSet()
	return mo.Fold(mo.TupleToResult(parser.ParseFile(files, serverplan.FileName, existing, parser.SkipObjectResolution)), func(file *ast.File) mo.Result[[]byte] {
		kept := []ast.Decl{}
		for _, declaration := range file.Decls {
			switch declared := declaration.(type) {
			case *ast.GenDecl:
				if declared.Tok != token.IMPORT {
					kept = append(kept, declared)
				}
			case *ast.FuncDecl:
				if declared.Name.IsExported() && declared.Recv.NumFields() == 0 {
					declared.Body = stubBody()
					kept = append(kept, declared)
				}
			case *ast.BadDecl, nil:
			}
		}
		file.Decls = append([]ast.Decl{usedImports(file, kept)}, kept...)
		file.Comments = []*ast.CommentGroup{}
		printed := &bytes.Buffer{}
		return mo.Fold(mo.EmptyableToOption(printer.Fprint(printed, files, file)), mo.Err[[]byte], func(error) mo.Result[[]byte] { return mo.Ok(printed.Bytes()) })
	}, mo.Err[[]byte])
}

// stubBody is the body every function of a stub has: a panic saying the routes are being read.
// The stub is only type-checked, never run.
func stubBody() *ast.BlockStmt {
	message := &ast.BasicLit{ValuePos: token.NoPos, ValueEnd: token.NoPos, Kind: token.STRING, Value: strconv.Quote("nocontract is reading the routes again")}
	call := &ast.CallExpr{Fun: ast.NewIdent("panic"), Lparen: token.NoPos, Args: []ast.Expr{message}, Ellipsis: token.NoPos, Rparen: token.NoPos}
	return &ast.BlockStmt{Lbrace: token.NoPos, List: []ast.Stmt{&ast.ExprStmt{X: call}}, Rbrace: token.NoPos}
}

// usedImports is the file's imports that the kept declarations refer to, each by the alias every
// generated import is written with, so the stub has no unused import.
func usedImports(file *ast.File, kept []ast.Decl) *ast.GenDecl {
	used := map[string]struct{}{}
	for _, declaration := range kept {
		ast.Inspect(declaration, func(node ast.Node) bool {
			if selector, isSelector := node.(*ast.SelectorExpr); isSelector {
				if qualifier, isIdentifier := selector.X.(*ast.Ident); isIdentifier {
					used[qualifier.Name] = struct{}{}
				}
			}
			return true
		})
	}
	specs := []ast.Spec{}
	for _, spec := range file.Imports {
		mo.Fold(mo.EmptyableToOption(spec.Name), func(alias *ast.Ident) struct{} {
			if _, isUsed := used[alias.Name]; isUsed {
				specs = append(specs, spec)
			}
			return struct{}{}
		}, func(error) struct{} { return struct{}{} })
	}
	return &ast.GenDecl{Doc: &ast.CommentGroup{List: []*ast.Comment{}}, TokPos: token.NoPos, Tok: token.IMPORT, Lparen: 1, Specs: specs, Rparen: 1}
}

// Render is the formatted Go file of the package.
func Render(served serverplan.Package) mo.Result[[]byte] {
	names := newImports(served.Path, served.Serves)
	body := &strings.Builder{}
	switch serves := served.Serves.(type) {
	case serverplan.ServesRoutes:
		body.WriteString(routesText(serves, names))
	case serverplan.ServesNoRoutes, nil:
	}
	for _, refusal := range served.Refusals {
		fmt.Fprintf(body, "\n// %s answers a refusal of the %s guard with its status, tag and code; the guard writes it\n// with nocontract.Write.", refusalFunction(refusal), refusal.Guard)
		body.WriteString(answerText(answerFunction{name: refusalFunction(refusal), sealed: refusal.Outcome.Name, members: refusal.Members}, names))
	}
	file := Header + "\npackage " + served.Name + "\n\n" + names.declaration() + "\n" + body.String()
	return mo.TupleToResult(format.Source([]byte(file)))
}

// exported is a name with its first letter in upper case, for the generated functions' names.
func exported(name string) string {
	first, size := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(first)) + name[size:]
}

// routesText is the Serving struct, the Routes function that needs it, and each route's handler,
// every outcome's answer following the first route that answers it.
func routesText(served serverplan.ServesRoutes, names *imports) string {
	text := &strings.Builder{}
	text.WriteString(servingText(served, names))
	unwritten := map[serverplan.GoName]serverplan.OutcomeAnswer{}
	for _, outcome := range served.Outcomes {
		unwritten[outcome.Outcome] = outcome
	}
	for _, route := range served.Routes {
		text.WriteString(routeText(route, names))
		if outcome, isUnwritten := unwritten[route.Outcome]; isUnwritten {
			delete(unwritten, route.Outcome)
			text.WriteString(answerText(answerFunction{name: outcomeFunction(outcome.Outcome, names), sealed: names.qualified(outcome.Outcome), members: outcome.Members}, names))
		}
	}
	return text.String()
}

// servingText is the Serving struct and the Routes function that needs it.
func servingText(served serverplan.ServesRoutes, names *imports) string {
	text := &strings.Builder{}
	fmt.Fprintf(text, "// %s is what this package's routes are served with: the receiver of each method handler\n// and each guard its routes name.\ntype %s struct {\n", serverplan.ServingType, serverplan.ServingType)
	for _, receiver := range served.Serving.Receivers {
		fmt.Fprintf(text, "\t%s %s\n", receiver.Name, names.qualified(receiver))
	}
	for _, guard := range served.Serving.Guards {
		fmt.Fprintf(text, "\t%s nocontract.Guard\n", guard)
	}
	fmt.Fprintf(text, "}\n\n// %s is every route this package declares, each behind the guard it names, or why a guard\n// cannot check one.\nfunc %s(serving %s) mo.Result[[]nocontract.Route] {\n\treturn nocontract.Collect(\n",
		serverplan.RoutesFunction, serverplan.RoutesFunction, serverplan.ServingType)
	for _, route := range served.Routes {
		serve := fmt.Sprintf("nocontractServe%s(serving)", exported(route.Name))
		switch guard := route.Guard.(type) {
		case serverplan.Guarded:
			fmt.Fprintf(text, "\t\tnocontract.GuardedBy(serving.%s, nocontract.GuardedRoute{Method: %s, Path: %s, Argument: %s}, %s),\n",
				guard.Name, strconv.Quote(route.Method.Name()), strconv.Quote(route.Path), strconv.Quote(guard.Argument), serve)
		case serverplan.Unguarded, nil:
			fmt.Fprintf(text, "\t\tnocontract.Served(nocontract.RouteAt{Method: %s, Path: %s}, %s),\n", strconv.Quote(route.Method.Name()), strconv.Quote(route.Path), serve)
		}
	}
	text.WriteString("\t)\n}\n")
	return text.String()
}

// handlerCall is the call that runs a route's handler on its input.
func handlerCall(handler serverplan.Handler) string {
	switch called := handler.(type) {
	case serverplan.FunctionHandler:
		return called.Name + "(request.Context(), input)"
	case serverplan.MethodHandler:
		return "serving." + called.Receiver + "." + called.Method + "(request.Context(), input)"
	case nil:
	}
	return ""
}

func routeText(route serverplan.Route, names *imports) string {
	name := exported(route.Name)
	text := &strings.Builder{}
	fmt.Fprintf(text, "\nfunc nocontractServe%s(serving %s) http.Handler {\n\treturn http.HandlerFunc(func(writer http.ResponseWriter, request *http.Request) {\n\t\tnocontract.Write(writer, nocontractAnswer%s(serving, request))\n\t})\n}\n",
		name, serverplan.ServingType, name)
	fmt.Fprintf(text, "\nfunc nocontractAnswer%s(serving %s, request *http.Request) nocontract.Answer {\n\tvar input %s\n", name, serverplan.ServingType, names.qualified(route.Input))
	steps := []string{}
	for _, param := range route.Params {
		steps = append(steps, paramStep(param, "nocontract.Path(request, "+strconv.Quote(param.Name)+")", names))
	}
	for _, param := range route.Query {
		steps = append(steps, paramStep(param, "nocontract.Query(request, "+strconv.Quote(param.Name)+")", names))
	}
	switch route.Body.(type) {
	case serverplan.BodyFieldRead:
		steps = append(steps, "return nocontract.Then(nocontract.Body(request, func(decoder *json.Decoder) error { return decoder.Decode(&input.Body) }), func(struct{}) nocontract.Answer {\n")
	case serverplan.NoBodyRead, nil:
	}
	for _, step := range steps {
		text.WriteString(step)
	}
	fmt.Fprintf(text, "return %s(%s)\n", outcomeFunction(route.Outcome, names), handlerCall(route.Handler))
	text.WriteString(strings.Repeat("})\n", len(steps)))
	text.WriteString("}\n")
	return text.String()
}

// paramStep opens the step that reads one parameter's text and sets its field.
func paramStep(param serverplan.Param, text string, names *imports) string {
	read := readCall(param.Text, text)
	return fmt.Sprintf("return nocontract.Then(%s, func(read %s) nocontract.Answer {\ninput.%s = %s(read)\n", read.call, read.value, param.GoField, names.qualified(param.GoType))
}

// textRead is the nocontract call reading a parameter's text, and the Go type of the value it reads.
type textRead struct {
	call  string
	value string
}

func readCall(kind serverplan.TextKind, text string) textRead {
	switch read := kind.(type) {
	case serverplan.TextAsIs:
		return textRead{call: "nocontract.Textual(" + text + ")", value: "string"}
	case serverplan.TextSigned:
		return textRead{call: fmt.Sprintf("nocontract.Signed(%s, %d)", text, read.Bits), value: "int64"}
	case serverplan.TextUnsigned:
		return textRead{call: fmt.Sprintf("nocontract.Unsigned(%s, %d)", text, read.Bits), value: "uint64"}
	case serverplan.TextTruth:
		return textRead{call: "nocontract.Truth(" + text + ")", value: "bool"}
	case serverplan.TextLiteral:
		values := []string{text}
		for _, value := range read.Values {
			values = append(values, strconv.Quote(value))
		}
		return textRead{call: "nocontract.Literal(" + strings.Join(values, ", ") + ")", value: "string"}
	case nil:
	}
	return textRead{call: "nocontract.Textual(" + text + ")", value: "string"}
}

// outcomeFunction is the generated function that answers a route outcome's members.
func outcomeFunction(outcome serverplan.GoName, names *imports) string {
	switch reference := names.reference(outcome.Package).(type) {
	case qualifiedBy:
		return "nocontractAnswer" + exported(reference.alias) + outcome.Name
	case unqualified, nil:
	}
	return "nocontractAnswer" + outcome.Name
}

// refusalFunction is the exported function a guard's refusal is answered through.
func refusalFunction(refusal serverplan.GuardRefusal) string {
	return serverplan.RefusalAnswerPrefix + refusal.Outcome.Name
}

// answerFunction is one generated function that answers each member of a sealed type: its name,
// the sealed type as the generated file writes it, and the members.
type answerFunction struct {
	name    string
	sealed  string
	members []serverplan.Member
}

// answerText is the function that answers each member of its sealed type with its status, tag and
// code.
func answerText(function answerFunction, names *imports) string {
	text := &strings.Builder{}
	fmt.Fprintf(text, "\nfunc %s(outcome %s) nocontract.Answer {\n\tswitch member := outcome.(type) {\n", function.name, function.sealed)
	for _, member := range function.members {
		fields := "mo.TupleToResult(json.Marshal(member))"
		switch answer := member.Answer.(type) {
		case description.Fails:
			fmt.Fprintf(text, "\tcase %s:\n\t\treturn nocontract.Failed(nocontract.Failure{Status: %d, Tag: %s, Code: %s, Fields: %s})\n",
				names.qualified(member.Go), answer.Status.Code(), strconv.Quote(member.Go.Name), strconv.Quote(answer.Code.String()), fields)
		case description.Succeeds:
			fmt.Fprintf(text, "\tcase %s:\n\t\treturn nocontract.Succeeded(nocontract.Success{Status: %d, Tag: %s, Fields: %s})\n",
				names.qualified(member.Go), answer.Status.Code(), strconv.Quote(member.Go.Name), fields)
		case nil:
		}
	}
	text.WriteString("\tcase nil:\n\t}\n\treturn nocontract.NoOutcome()\n}\n")
	return text.String()
}

// imports names every package the generated file refers to, each foreign package by an alias of
// its own.
type imports struct {
	home    string
	aliases map[string]string
	order   []string
}

// fixedImports are the packages a generated file imports by the names it uses: net/http only when
// it serves routes.
func fixedImports(serves serverplan.Routing) [][2]string {
	fixed := [][2]string{{"encoding/json", "json"}, {"github.com/samber/mo", "mo"}, {serverplan.NoContractPath, "nocontract"}}
	switch serves.(type) {
	case serverplan.ServesRoutes:
		return append(fixed, [2]string{"net/http", "http"})
	case serverplan.ServesNoRoutes, nil:
	}
	return fixed
}

func newImports(home string, serves serverplan.Routing) *imports {
	names := &imports{home: home, aliases: map[string]string{}, order: []string{}}
	for _, fixed := range fixedImports(serves) {
		names.aliases[fixed[0]] = fixed[1]
		names.order = append(names.order, fixed[0])
	}
	return names
}

// reference is how the generated file refers to a type of the package at path: by its bare name for
// its own package or a predeclared type, and through a unique alias for any other, which the file
// then imports.
func (names *imports) reference(path string) reference {
	if path == "" || path == names.home {
		return unqualified{}
	}
	if alias, known := names.aliases[path]; known {
		return qualifiedBy{alias: alias}
	}
	base := path[strings.LastIndex(path, "/")+1:]
	cleaned := strings.Map(func(letter rune) rune {
		if unicode.IsLetter(letter) || unicode.IsDigit(letter) {
			return letter
		}
		return '_'
	}, base)
	taken := append(slices.Collect(maps.Values(names.aliases)), localNames()...)
	alias := cleaned
	for suffix := 2; slices.Contains(taken, alias); suffix++ {
		alias = cleaned + strconv.Itoa(suffix)
	}
	names.aliases[path] = alias
	names.order = append(names.order, path)
	return qualifiedBy{alias: alias}
}

// reference is how the generated file refers to a type of a package: by its bare name, or through
// the package's alias.
//
//sumtype:decl
type reference interface{ isReference() }

// unqualified is a type of the file's own package, or a predeclared type, written by its name.
//
//ergo:not-an-error
type unqualified struct{}

// qualifiedBy is a type of another package, written through that package's alias.
//
//ergo:not-an-error
type qualifiedBy struct{ alias string }

func (unqualified) isReference() {}
func (qualifiedBy) isReference() {}

// localNames are the names the generated functions give their parameters and variables, which no
// package alias may take.
func localNames() []string {
	return []string{"input", "read", "request", "writer", "outcome", "member", "serving", "http", "json", "mo", "nocontract"}
}

// qualified is a Go name as the generated file writes it.
func (names *imports) qualified(name serverplan.GoName) string {
	switch reference := names.reference(name.Package).(type) {
	case qualifiedBy:
		return reference.alias + "." + name.Name
	case unqualified, nil:
	}
	return name.Name
}

func (names *imports) declaration() string {
	lines := []string{}
	for _, path := range names.order {
		lines = append(lines, "\t"+names.aliases[path]+" "+strconv.Quote(path))
	}
	return "import (\n" + strings.Join(lines, "\n") + "\n)\n"
}
