// Package writing writes the Go file that serves one package's routes: a Routes function, one
// function per route that reads its input from the request and runs its handler, and one
// exhaustive switch per outcome that writes each member with its tag, status and code.
package writing

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/samber/mo"

	"github.com/CheckPickerUpper/nocontract/go/serverplan"
)

// Header opens every file NoContract writes.
const Header = "// Code generated by nocontract. DO NOT EDIT.\n"

// NoContractPath is the import path of the Go package the generated code is built from.
const NoContractPath = "github.com/CheckPickerUpper/nocontract/go"

// Stub is the generated file of a package named name before its routes are read: the same exported
// Routes, serving nothing, so code that calls it still compiles while the routes are read.
func Stub(name string) []byte {
	return []byte(Header + "\npackage " + name + "\n\nimport nocontract \"" + NoContractPath + "\"\n\n" +
		"// Routes is every route this package declares.\nfunc Routes() []nocontract.Route { return []nocontract.Route{} }\n")
}

// Render is the formatted Go file serving the package's routes.
func Render(served serverplan.Package) mo.Result[[]byte] {
	names := newImports(served.Path)
	body := &strings.Builder{}
	body.WriteString("// Routes is every route this package declares.\nfunc Routes() []nocontract.Route {\n\treturn []nocontract.Route{\n")
	for _, route := range served.Routes {
		fmt.Fprintf(body, "\t\tnocontract.NewRoute(%s, %s, nocontractServe%s),\n", strconv.Quote(route.Method), strconv.Quote(route.Path), exported(route.Handler.Name))
	}
	body.WriteString("\t}\n}\n")
	answered := map[serverplan.GoName]struct{}{}
	for _, route := range served.Routes {
		body.WriteString(routeText(route, names))
		if _, written := answered[route.Outcome]; !written {
			answered[route.Outcome] = struct{}{}
			body.WriteString(outcomeText(route, names))
		}
	}
	file := Header + "\npackage " + served.Name + "\n\n" + names.declaration() + "\n" + body.String()
	return mo.TupleToResult(format.Source([]byte(file)))
}

// exported is a name with its first letter in upper case, for the generated functions' names.
func exported(name string) string {
	if name == "" {
		return ""
	}
	first, size := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(first)) + name[size:]
}

func routeText(route serverplan.Route, names *imports) string {
	handler := exported(route.Handler.Name)
	text := &strings.Builder{}
	fmt.Fprintf(text, "\nfunc nocontractServe%s(writer http.ResponseWriter, request *http.Request) {\n\tnocontract.Write(writer, nocontractAnswer%s(request))\n}\n", handler, handler)
	fmt.Fprintf(text, "\nfunc nocontractAnswer%s(request *http.Request) nocontract.Answer {\n\tvar input %s\n", handler, names.qualified(route.Input))
	steps := []string{}
	for _, param := range route.Params {
		steps = append(steps, paramStep(param, "nocontract.Path(request, "+strconv.Quote(param.Name)+")", names))
	}
	for _, param := range route.Query {
		steps = append(steps, paramStep(param, "nocontract.Query(request, "+strconv.Quote(param.Name)+")", names))
	}
	switch route.Body.(type) {
	case serverplan.BodyFieldRead:
		steps = append(steps, "return nocontract.Then(nocontract.Body(request, func(decoder *json.Decoder) error { return decoder.Decode(&input.Body) }), func(struct{}) nocontract.Answer {\n")
	case serverplan.NoBodyRead, nil:
	}
	for _, step := range steps {
		text.WriteString(step)
	}
	fmt.Fprintf(text, "return %s(%s(request.Context(), input))\n", outcomeFunction(route.Outcome, names), route.Handler.Name)
	text.WriteString(strings.Repeat("})\n", len(steps)))
	text.WriteString("}\n")
	return text.String()
}

// paramStep opens the step that reads one parameter's text and sets its field.
func paramStep(param serverplan.Param, text string, names *imports) string {
	read, value := readCall(param.Text, text)
	return fmt.Sprintf("return nocontract.Then(%s, func(read %s) nocontract.Answer {\ninput.%s = %s(read)\n", read, value, param.GoField, names.qualified(param.GoType))
}

// readCall is the nocontract call reading text as kind, and the Go type of the value it reads.
func readCall(kind serverplan.TextKind, text string) (string, string) {
	switch read := kind.(type) {
	case serverplan.TextAsIs:
		return "nocontract.Textual(" + text + ")", "string"
	case serverplan.TextSigned:
		return fmt.Sprintf("nocontract.Signed(%s, %d)", text, read.Bits), "int64"
	case serverplan.TextUnsigned:
		return fmt.Sprintf("nocontract.Unsigned(%s, %d)", text, read.Bits), "uint64"
	case serverplan.TextTruth:
		return "nocontract.Truth(" + text + ")", "bool"
	case serverplan.TextLiteral:
		values := []string{text}
		for _, value := range read.Values {
			values = append(values, strconv.Quote(value))
		}
		return "nocontract.Literal(" + strings.Join(values, ", ") + ")", "string"
	case nil:
	}
	return "nocontract.Textual(" + text + ")", "string"
}

// outcomeFunction is the generated function that answers an outcome's members.
func outcomeFunction(outcome serverplan.GoName, names *imports) string {
	return "nocontractAnswer" + exported(names.alias(outcome.Package)) + outcome.Name
}

func outcomeText(route serverplan.Route, names *imports) string {
	text := &strings.Builder{}
	fmt.Fprintf(text, "\nfunc %s(outcome %s) nocontract.Answer {\n\tswitch member := outcome.(type) {\n", outcomeFunction(route.Outcome, names), names.qualified(route.Outcome))
	for _, member := range route.Members {
		fields := "mo.TupleToResult(json.Marshal(member))"
		switch code := member.Code.(type) {
		case serverplan.Coded:
			fmt.Fprintf(text, "\tcase %s:\n\t\treturn nocontract.Failed(%d, %s, %s, %s)\n", names.qualified(member.Go), member.Status, strconv.Quote(member.Tag), strconv.Quote(code.Code), fields)
		case serverplan.NoCode, nil:
			fmt.Fprintf(text, "\tcase %s:\n\t\treturn nocontract.Succeeded(%d, %s, %s)\n", names.qualified(member.Go), member.Status, strconv.Quote(member.Tag), fields)
		}
	}
	text.WriteString("\tcase nil:\n\t}\n\treturn nocontract.NoOutcome()\n}\n")
	return text.String()
}

// imports names every package the generated file refers to, each foreign package by an alias of
// its own.
type imports struct {
	home    string
	aliases map[string]string
	order   []string
}

// fixedImports are the packages every generated file imports, by the names it uses.
func fixedImports() [][2]string {
	return [][2]string{{"encoding/json", "json"}, {"net/http", "http"}, {"github.com/samber/mo", "mo"}, {NoContractPath, "nocontract"}}
}

func newImports(home string) *imports {
	names := &imports{home: home, aliases: map[string]string{}, order: []string{}}
	for _, fixed := range fixedImports() {
		names.aliases[fixed[0]] = fixed[1]
		names.order = append(names.order, fixed[0])
	}
	return names
}

// alias is the name the generated file refers to a package by: nothing for its own package or a
// predeclared type, and a unique alias for any other.
func (names *imports) alias(path string) string {
	if path == "" || path == names.home {
		return ""
	}
	if alias, known := names.aliases[path]; known {
		return alias
	}
	base := path[strings.LastIndex(path, "/")+1:]
	cleaned := strings.Map(func(letter rune) rune {
		if unicode.IsLetter(letter) || unicode.IsDigit(letter) {
			return letter
		}
		return '_'
	}, base)
	alias := cleaned
	for suffix := 2; names.taken(alias); suffix++ {
		alias = cleaned + strconv.Itoa(suffix)
	}
	names.aliases[path] = alias
	names.order = append(names.order, path)
	return alias
}

func (names *imports) taken(alias string) bool {
	for _, used := range names.aliases {
		if used == alias {
			return true
		}
	}
	return alias == "input" || alias == "read" || alias == "request" || alias == "writer" || alias == "outcome" || alias == "member"
}

// qualified is a Go name as the generated file writes it.
func (names *imports) qualified(name serverplan.GoName) string {
	if alias := names.alias(name.Package); alias != "" {
		return alias + "." + name.Name
	}
	return name.Name
}

func (names *imports) declaration() string {
	lines := []string{}
	for _, path := range names.order {
		lines = append(lines, "\t"+names.aliases[path]+" "+strconv.Quote(path))
	}
	return "import (\n" + strings.Join(lines, "\n") + "\n)\n"
}
